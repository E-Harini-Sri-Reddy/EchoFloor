function revisionFor(memory: MemoryRecord): MemoryRevision {
  return {
    id: `rev_${memory.id}_1`,
    organisationId: memory.organisationId,
    memoryId: memory.id,
    revisionNumber: 1,
    snapshot: {
      type: memory.type,
      title: memory.title,
      content: memory.content,
      summary: memory.summary,
      status: memory.status,
      tags: memory.tags,
    },
    changeSummary: "Initial example record",
    changedBy: memory.createdBy,
    createdAt: memory.createdAt,
  };
}

