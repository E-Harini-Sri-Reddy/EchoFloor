function membership(
  organisationId: string,
  userId: string,
  role: Membership["role"],
  workerAccess?: Pick<
    Membership,
    "workerAccessType" | "accessDurationPreset" | "accessExpiresAt"
  >,
): Membership {
  return {
    id: `memship_${organisationId}_${userId}`,
    organisationId,
    userId,
    role,
    status: "active",
    ...(role === "worker"
      ? {
          workerAccessType: workerAccess?.workerAccessType ?? "permanent",
          accessDurationPreset: workerAccess?.accessDurationPreset ?? "until_removed",
          accessExpiresAt: workerAccess?.accessExpiresAt ?? null,
        }
      : {}),
    joinedAt: created,
    createdAt: created,
    updatedAt: created,
  };
}

